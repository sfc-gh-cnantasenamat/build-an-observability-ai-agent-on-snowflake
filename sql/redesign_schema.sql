-- Redesign schema additions (additive; existing cohorts keep their verdicts).
-- Policy change: refund window shrinks from 30 to 14 days on 2026-11-07. Earlier
-- cohorts were decided on 2026-11-06 under P_2026 and are unaffected.
UPDATE REFUND_AGENT_LAB.DEMO.POLICIES
   SET EFFECTIVE_TO = '2026-11-07T00:00:00+00:00'::TIMESTAMP_TZ
 WHERE POLICY_ID = 'P_2026' AND EFFECTIVE_TO IS NULL;
INSERT INTO REFUND_AGENT_LAB.DEMO.POLICIES (POLICY_ID, EFFECTIVE_FROM, EFFECTIVE_TO, MAX_AGE_DAYS)
SELECT 'P_2026_14D', '2026-11-07T00:00:00+00:00'::TIMESTAMP_TZ, NULL, 14
WHERE NOT EXISTS (SELECT 1 FROM REFUND_AGENT_LAB.DEMO.POLICIES WHERE POLICY_ID = 'P_2026_14D');

-- Payment state: pending payments have nothing settled; a closed card makes the
-- simulated processor decline the refund.
ALTER TABLE REFUND_AGENT_LAB.DEMO.PAYMENTS ADD COLUMN IF NOT EXISTS PAYMENT_STATUS VARCHAR DEFAULT 'settled';
ALTER TABLE REFUND_AGENT_LAB.DEMO.PAYMENTS ADD COLUMN IF NOT EXISTS PROCESSOR_STATUS VARCHAR DEFAULT 'ok';

-- What the agent believed and said.
ALTER TABLE REFUND_AGENT_LAB.DEMO.RUNS ADD COLUMN IF NOT EXISTS AGENT_POLICY_ID VARCHAR;
ALTER TABLE REFUND_AGENT_LAB.DEMO.RUNS ADD COLUMN IF NOT EXISTS REPLY VARCHAR;
ALTER TABLE REFUND_AGENT_LAB.DEMO.RUNS ADD COLUMN IF NOT EXISTS ORDER_TOTAL_CENTS NUMBER;

-- One row per model call, for cost and latency.
CREATE TABLE IF NOT EXISTS REFUND_AGENT_LAB.DEMO.LLM_CALLS (
  RUN_ID VARCHAR, NODE VARCHAR, MODEL VARCHAR,
  INPUT_TOKENS NUMBER, OUTPUT_TOKENS NUMBER, LATENCY_MS FLOAT,
  EST_COST_USD FLOAT, CALLED_AT TIMESTAMP_TZ
);

-- Model cost in Snowflake AI credits (estimated from token counts and published rates).
ALTER TABLE REFUND_AGENT_LAB.DEMO.RUNS ADD COLUMN IF NOT EXISTS MODEL_COST_CREDITS FLOAT;
ALTER TABLE REFUND_AGENT_LAB.DEMO.LLM_CALLS ADD COLUMN IF NOT EXISTS EST_CREDITS FLOAT;
